import { tidy, type MessageBuilder } from "./types";

export const buildKannada: MessageBuilder = (status, v) => {
  const pins = v.suggestedPins.join(" ಅಥವಾ ");
  const place = v.pin ? `ಪಿನ್ ${v.pin}` : v.city;

  switch (status) {
    case "APPROVED":
      return tidy([
        `ನಮಸ್ಕಾರ ${v.name}, ${v.brandName} ಕಡೆಯಿಂದ ಒಳ್ಳೆಯ ಸುದ್ದಿ.`,
        `${v.city} ನ ${place} ಗಾಗಿ ನಿಮ್ಮ ಫ್ರಾಂಚೈಸಿ ಅರ್ಜಿ ಅನುಮೋದನೆಗೊಂಡಿದೆ.`,
        "ಈ ವಾರವೇ ದಾಖಲೆಗಳು ಮತ್ತು KYC ಪ್ರಾರಂಭಿಸಿ ಫ್ರಾಂಚೈಸಿ ಒಪ್ಪಂದ ನೀಡುತ್ತೇವೆ.",
        v.trainingStore && v.trainingWeeks
          ? `ನಿಮ್ಮ ತರಬೇತಿ ${v.trainingStore} ನಲ್ಲಿ ${v.trainingWeeks} ವಾರಗಳ ಕಾಲ ನಡೆಯಲಿದೆ.`
          : null,
        v.launchDate ? `ನಿಗದಿತ ಪ್ರಾರಂಭ ದಿನಾಂಕ ${v.launchDate}.` : null,
        "ಎರಡು ಕೆಲಸದ ದಿನಗಳಲ್ಲಿ ನಮ್ಮ ಆನ್‌ಬೋರ್ಡಿಂಗ್ ವ್ಯವಸ್ಥಾಪಕರು ನಿಮಗೆ ಕರೆ ಮಾಡುತ್ತಾರೆ.",
      ]);

    case "WAITLISTED":
      return tidy([
        `ನಮಸ್ಕಾರ ${v.name}, ${v.brandName} ಗೆ ಅರ್ಜಿ ಸಲ್ಲಿಸಿದ್ದಕ್ಕೆ ಧನ್ಯವಾದಗಳು.`,
        `${v.city} ಗಾಗಿ ನಿಮ್ಮ ಅರ್ಜಿ ಪೂರ್ಣವಾಗಿದ್ದು ನಮ್ಮ ಎಲ್ಲಾ ಅವಶ್ಯಕತೆಗಳನ್ನು ಪೂರೈಸುತ್ತದೆ, ಆದರೆ ಈ ಪ್ರದೇಶದ ಎಲ್ಲಾ ಸ್ಥಾನಗಳು ಸದ್ಯಕ್ಕೆ ಭರ್ತಿಯಾಗಿವೆ.`,
        "ನೀವು ಕಾಯುವ ಪಟ್ಟಿಯಲ್ಲಿದ್ದೀರಿ, ಸ್ಥಾನ ಖಾಲಿಯಾದ ತಕ್ಷಣ ನಾವು ಸಂಪರ್ಕಿಸುತ್ತೇವೆ.",
        "ಸದ್ಯಕ್ಕೆ ನಿಮ್ಮಿಂದ ಬೇರೇನೂ ಬೇಕಾಗಿಲ್ಲ.",
      ]);

    case "ON HOLD":
      return tidy([
        `ನಮಸ್ಕಾರ ${v.name}, ${v.brandName} ಗೆ ಅರ್ಜಿ ಸಲ್ಲಿಸಿದ್ದಕ್ಕೆ ಧನ್ಯವಾದಗಳು.`,
        `ಒಂದು ವಿವರವನ್ನು ಖಚಿತಪಡಿಸುವವರೆಗೆ ${v.city} ಗಾಗಿ ನಿಮ್ಮ ಅರ್ಜಿಯನ್ನು ತಡೆಹಿಡಿಯಲಾಗಿದೆ.`,
        v.unlockCondition,
        v.reservedUntil && v.pin
          ? `ಪಿನ್ ${v.pin} ಅನ್ನು ${v.reservedUntil} ವರೆಗೆ ನಿಮಗಾಗಿ ಕಾಯ್ದಿರಿಸಲಾಗಿದೆ.`
          : null,
        "ದಯವಿಟ್ಟು ಈ ಮಾಹಿತಿಯನ್ನು ಕಳುಹಿಸಿ, ನಾವು ತಕ್ಷಣ ಮುಂದುವರಿಯುತ್ತೇವೆ.",
      ]);

    case "REDIRECTED":
      return tidy([
        `ನಮಸ್ಕಾರ ${v.name}, ${v.brandName} ಗೆ ಅರ್ಜಿ ಸಲ್ಲಿಸಿದ್ದಕ್ಕೆ ಧನ್ಯವಾದಗಳು.`,
        v.pin
          ? `ಪಿನ್ ${v.pin} ನಲ್ಲಿ ನಾವು ಹೊಸ ಅಂಗಡಿ ತೆರೆಯಲು ಸಾಧ್ಯವಿಲ್ಲ,`
          : "ನೀಡಿರುವ ಸ್ಥಳದಲ್ಲಿ ನಾವು ಹೊಸ ಅಂಗಡಿ ತೆರೆಯಲು ಸಾಧ್ಯವಿಲ್ಲ,",
        pins ? `ಆದರೆ ಹತ್ತಿರದಲ್ಲಿ ${pins} ಲಭ್ಯವಿದೆ.` : "ಆದರೆ ಸ್ಥಳ ಖಾಲಿಯಾದ ತಕ್ಷಣ ಬೇರೆ ಪಿನ್ ಕೋಡ್ ತಿಳಿಸುತ್ತೇವೆ.",
        pins ? `${pins} ನಲ್ಲಿ ಜಾಗ ಸಿಕ್ಕರೆ ನಿಮ್ಮ ಅರ್ಜಿಯನ್ನು ಮುಂದುವರಿಸಲು ನಮಗೆ ಸಂತೋಷ.` : null,
        "ಇದು ತಿರಸ್ಕಾರವಲ್ಲ.",
      ]);

    case "NOT PROCEEDING":
      return tidy([
        `ನಮಸ್ಕಾರ ${v.name}, ${v.brandName} ಬಗ್ಗೆ ಆಸಕ್ತಿ ತೋರಿಸಿದ್ದಕ್ಕೆ ಧನ್ಯವಾದಗಳು.`,
        "ಸದ್ಯಕ್ಕೆ ಈ ಅರ್ಜಿಯನ್ನು ಮುಂದುವರಿಸಲು ನಮಗೆ ಸಾಧ್ಯವಾಗುತ್ತಿಲ್ಲ.",
        v.unlockCondition,
        "ನಿಮ್ಮ ಅರ್ಜಿ ನಮ್ಮ ದಾಖಲೆಯಲ್ಲಿ ಉಳಿಯುತ್ತದೆ, ಪರಿಸ್ಥಿತಿ ಬದಲಾದರೆ ನಾವು ಸಂಪರ್ಕಿಸುತ್ತೇವೆ.",
      ]);
  }
};
